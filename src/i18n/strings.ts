export const STRINGS: Record<Lang, Strings> = { en, de, sv }

export const LANG_LABELS: Record<Lang, string> = { en: 'English', de: 'Deutsch', sv: 'Svenska' }

type StringKey = { [K in keyof Strings]: Strings[K] extends string ? K : never }[keyof Strings]

export function format(s: string, vars?: Record<string, string | number>): string {
  if (!vars) return s
  return s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`))
}

export function makeT(lang: Lang) {
  const dict = STRINGS[lang]
  const t = (key: StringKey, vars?: Record<string, string | number>) => format(dict[key], vars)
  return Object.assign(t, { dict })
}

export type T = ReturnType<typeof makeT>
